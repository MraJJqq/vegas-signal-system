"""Download real Bitget GOLD (XAUUSDT) candles for V1 data integration.\n\nThe workflow uploads the CSV and JSON report as a GitHub Actions artifact.

Fetches closed 1H and 4H candles and aggregates 2H/8H only from complete,
contiguous 1H candles. No signals or trades are generated by this script.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from datetime import datetime, timedelta, timezone
from pathlib import Path

from bitget_market_data import BitgetMarketDataError, HistoricalCandle, candles_to_csv_rows, fetch_history_candles

TIMEFRAMES = {"1H": 1, "2H": 2, "4H": 4, "8H": 8}


def aggregate_hourly(hourly: list[HistoricalCandle], timeframe: str) -> list[HistoricalCandle]:
    hours = TIMEFRAMES[timeframe]
    buckets: dict[datetime, list[HistoricalCandle]] = defaultdict(list)
    for candle in hourly:
        epoch_hour = int(candle.timestamp.timestamp() // 3600)
        bucket_start = datetime.fromtimestamp((epoch_hour // hours) * hours * 3600, tz=timezone.utc)
        buckets[bucket_start].append(candle)

    result = []
    for start, bars in sorted(buckets.items()):
        bars.sort(key=lambda x: x.timestamp)
        expected = [start + timedelta(hours=i) for i in range(hours)]
        if [bar.timestamp for bar in bars] != expected:
            continue
        result.append(HistoricalCandle(
            symbol=bars[0].symbol,
            timeframe=timeframe,
            timestamp=start,
            open=bars[0].open,
            high=max(x.high for x in bars),
            low=min(x.low for x in bars),
            close=bars[-1].close,
            base_volume=sum(x.base_volume for x in bars),
            quote_volume=sum(x.quote_volume for x in bars),
        ))
    return result


def fetch_preferred_timeframe(symbol: str, timeframe: str, start: datetime, end: datetime, hourly: list[HistoricalCandle] | None = None) -> tuple[list[HistoricalCandle], str]:
    """Prefer Bitget's native timeframe; aggregate only when it is unavailable."""
    try:
        native = fetch_history_candles(symbol=symbol, timeframe=timeframe, start=start, end=end)
        if native:
            return native, "Bitget native"
    except (BitgetMarketDataError, ValueError):
        pass
    if timeframe == "1H":
        raise RuntimeError(f"Bitget returned no native 1H candles for {symbol}")
    base = hourly if hourly is not None else fetch_history_candles(
        symbol=symbol, timeframe="1H", start=start, end=end
    )
    aggregated = aggregate_hourly(base, timeframe)
    if not aggregated:
        raise RuntimeError(f"Neither native nor aggregated {timeframe} candles available for {symbol}")
    return aggregated, "aggregated from complete contiguous 1H candles (native unavailable)"


def download(symbol: str, days: int, output_dir: Path) -> dict:
    if days < 30 or days > 730:
        raise ValueError("--days must be between 30 and 730")
    end = datetime.now(timezone.utc)
    start = end - timedelta(days=days)
    # Every timeframe is requested natively first. Hourly bars are used only as fallback.
    hourly = fetch_history_candles(symbol=symbol, timeframe="1H", start=start, end=end)
    if not hourly:
        raise RuntimeError(f"Bitget returned no closed 1H candles for {symbol}")
    series = {"1H": hourly}
    source_by_timeframe = {"1H": "Bitget native"}
    for timeframe in ("2H", "4H", "8H"):
        candles, source = fetch_preferred_timeframe(symbol, timeframe, start, end, hourly)
        series[timeframe] = candles
        source_by_timeframe[timeframe] = source
    output_dir.mkdir(parents=True, exist_ok=True)
    all_rows = []
    counts = {}
    for timeframe, candles in series.items():
        if not candles:
            raise RuntimeError(f"No complete {timeframe} candles produced for {symbol}")
        counts[timeframe] = len(candles)
        all_rows.extend(candles_to_csv_rows(candles))

    all_rows.sort(key=lambda row: (row["timeframe"], row["timestamp"]))
    csv_path = output_dir / "gold_candles.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(all_rows[0].keys()))
        writer.writeheader()
        writer.writerows(all_rows)

    report = {
        "status": "success",
        "provider": "Bitget USDT-FUTURES public market data",
        "symbol": symbol.upper(),
        "range_start_utc": start.isoformat(),
        "range_end_utc": end.isoformat(),
        "timeframes": counts,
        "total_candles": len(all_rows),
        "closed_candles_only": True,
        "timeframe_source": source_by_timeframe,
        "aggregation_policy": "Prefer Bitget native candles for every timeframe; aggregate from complete contiguous 1H bars only when native candles are unavailable",
        "signals_generated": False,
        "note": "This validates market-data connectivity only; Vegas signal generation and trade backtesting are separate steps.",
    }
    (output_dir / "gold_data_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Download Bitget GOLD history for V1.")
    parser.add_argument("--symbol", default="XAUUSDT")
    parser.add_argument("--days", type=int, default=180)
    parser.add_argument("--output-dir", type=Path, default=Path("output"))
    args = parser.parse_args()
    download(args.symbol, args.days, args.output_dir)
